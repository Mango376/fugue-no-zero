export function buildWorldBookInjection(ids = []) {
  const requestedIds = Array.isArray(ids) && ids.length > 0
    ? new Set(ids)
    : null

  return WORLD_BOOK
    .filter(entry => !requestedIds || requestedIds.has(entry.id))
    .map(entry => `【${entry.title}】\n${entry.content}`)
    .join('\n\n')
}
